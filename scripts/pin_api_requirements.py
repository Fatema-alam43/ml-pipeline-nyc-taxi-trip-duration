"""Pin requirements-api.txt to the exact versions in requirements-lock.txt.

The API image then uses the same package versions as training (important for LightGBM and pandas).
    python scripts/pin_api_requirements.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API_PACKAGES = ["fastapi", "pydantic", "starlette", "uvicorn", "numpy", "pandas", "lightgbm", "scipy",
                "pyyaml", "boto3", "tzdata"]


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def main() -> None:
    locked = {}
    for line in (ROOT / "requirements-lock.txt").read_text().splitlines():
        if "==" in line and not line.startswith("#"):
            name, version = line.split("==", 1)
            locked[normalise(name)] = (name, version.strip())
    missing = [p for p in API_PACKAGES if normalise(p) not in locked]
    if missing:
        raise SystemExit(f"Not in requirements-lock.txt: {missing}. Install requirements.txt and re-run pip freeze.")
    lines = ["# Packages for the API Docker image, pinned to the training versions.",
             "# Generated by scripts/pin_api_requirements.py - do not edit by hand."]
    lines += [f"{locked[normalise(p)][0]}=={locked[normalise(p)][1]}" for p in API_PACKAGES]
    (ROOT / "requirements-api.txt").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[2:]))


if __name__ == "__main__":
    main()
